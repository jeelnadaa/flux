//! Test corpus manifest representation, parser, synthetic generator, and integrity verifier.
//!
//! Enforces PLAN.md Appendix A specifications:
//! - Documented licences and SHA-256 hashes for all corpus entries.
//! - Small, self-generated synthetic files checked into git.
//! - Automated integrity tests verifying files match manifest hashes and WAV metadata.

use crate::generators::{
    chirp_linear, chirp_log, dc, impulse, multitone, pink_noise, silence, sine, white_noise,
};
use crate::sha256::sha256_digest;
use crate::wav::{decode_wav, encode_wav, WavFormat};
use std::fs;
use std::path::Path;

/// Individual entry in the test corpus manifest.
#[derive(Debug, Clone, PartialEq)]
pub struct CorpusEntry {
    /// Unique identifier for this audio clip or test asset.
    pub id: String,
    /// Relative path from repository root.
    pub path: String,
    /// Provenance, authoring tool, or dataset URL.
    pub source: String,
    /// SPDX licence identifier or documented licence term.
    pub licence: String,
    /// 64-character lowercase hexadecimal SHA-256 digest of the audio file.
    pub sha256: String,
    /// Nominal audio duration in seconds.
    pub duration: f32,
    /// Sampling rate in Hz.
    pub sample_rate: u32,
    /// Channel count (e.g. 1 for mono, 2 for stereo, 6 for 5.1).
    pub channels: usize,
    /// Category and property tags.
    pub tags: Vec<String>,
    /// Test types and suites that utilize this fixture.
    pub expected_test_uses: Vec<String>,
    /// Whether this file is synthetic and generated by Flux test tooling.
    pub synthetic: bool,
}

/// The complete corpus manifest structure.
#[derive(Debug, Clone, PartialEq)]
pub struct CorpusManifest {
    /// Manifest schema version.
    pub version: u32,
    /// Human-readable description.
    pub description: String,
    /// List of corpus entries.
    pub entries: Vec<CorpusEntry>,
}

/// Result of running the corpus manifest and file integrity check.
#[derive(Debug, Clone, Default)]
pub struct IntegrityReport {
    /// Total entries defined in manifest.
    pub total_entries: usize,
    /// Number of synthetic entries.
    pub synthetic_entries: usize,
    /// Number of external corpus entries.
    pub external_entries: usize,
    /// Number of corpus files present on disk.
    pub files_present: usize,
    /// Number of files verified with matching SHA-256 and audio metadata.
    pub files_verified: usize,
    /// List of verification failures or errors encountered.
    pub failures: Vec<String>,
}

impl IntegrityReport {
    /// Returns true if all checked files passed with zero failures.
    pub fn is_valid(&self) -> bool {
        self.failures.is_empty() && self.files_verified >= self.synthetic_entries
    }
}

/// Parses a `corpus.yaml` string into a structured `CorpusManifest`.
pub fn parse_manifest_yaml(yaml: &str) -> Result<CorpusManifest, String> {
    let mut version = 1u32;
    let mut description = String::new();
    let mut entries = Vec::new();

    let mut current_entry: Option<CorpusEntryBuilder> = None;
    let mut in_tags = false;
    let mut in_test_uses = false;

    for (line_num, raw_line) in yaml.lines().enumerate() {
        let trimmed = raw_line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }

        if let Some(rest) = trimmed.strip_prefix("version:") {
            version = rest
                .trim()
                .parse::<u32>()
                .map_err(|e| format!("Line {}: invalid version number: {}", line_num + 1, e))?;
            continue;
        }

        if let Some(rest) = trimmed.strip_prefix("description:") {
            description = rest.trim().trim_matches('"').trim_matches('\'').to_string();
            continue;
        }

        if trimmed == "corpus:" {
            continue;
        }

        // Check for new entry starting with "- id:"
        if let Some(rest) = trimmed.strip_prefix("- id:") {
            if let Some(b) = current_entry.take() {
                entries.push(b.build(line_num)?);
            }
            let b = CorpusEntryBuilder {
                id: Some(rest.trim().trim_matches('"').trim_matches('\'').to_string()),
                ..Default::default()
            };
            current_entry = Some(b);
            in_tags = false;
            in_test_uses = false;
            continue;
        }

        // Inside entry attributes
        if let Some(ref mut b) = current_entry {
            if trimmed.starts_with("tags:") {
                in_tags = true;
                in_test_uses = false;
                continue;
            }
            if trimmed.starts_with("expected_test_uses:") {
                in_test_uses = true;
                in_tags = false;
                continue;
            }

            if in_tags {
                if let Some(tag) = trimmed.strip_prefix('-') {
                    b.tags
                        .push(tag.trim().trim_matches('"').trim_matches('\'').to_string());
                    continue;
                } else if trimmed.contains(':') {
                    in_tags = false;
                }
            }

            if in_test_uses {
                if let Some(use_case) = trimmed.strip_prefix('-') {
                    b.expected_test_uses.push(
                        use_case
                            .trim()
                            .trim_matches('"')
                            .trim_matches('\'')
                            .to_string(),
                    );
                    continue;
                } else if trimmed.contains(':') {
                    in_test_uses = false;
                }
            }

            if let Some(rest) = trimmed.strip_prefix("path:") {
                b.path = Some(rest.trim().trim_matches('"').trim_matches('\'').to_string());
            } else if let Some(rest) = trimmed.strip_prefix("source:") {
                b.source = Some(rest.trim().trim_matches('"').trim_matches('\'').to_string());
            } else if let Some(rest) = trimmed.strip_prefix("licence:") {
                b.licence = Some(rest.trim().trim_matches('"').trim_matches('\'').to_string());
            } else if let Some(rest) = trimmed.strip_prefix("license:") {
                b.licence = Some(rest.trim().trim_matches('"').trim_matches('\'').to_string());
            } else if let Some(rest) = trimmed.strip_prefix("sha256:") {
                b.sha256 = Some(rest.trim().trim_matches('"').trim_matches('\'').to_string());
            } else if let Some(rest) = trimmed.strip_prefix("duration:") {
                b.duration = Some(
                    rest.trim()
                        .parse::<f32>()
                        .map_err(|e| format!("Line {}: invalid duration: {}", line_num + 1, e))?,
                );
            } else if let Some(rest) = trimmed.strip_prefix("sample_rate:") {
                b.sample_rate =
                    Some(rest.trim().parse::<u32>().map_err(|e| {
                        format!("Line {}: invalid sample_rate: {}", line_num + 1, e)
                    })?);
            } else if let Some(rest) = trimmed.strip_prefix("channels:") {
                b.channels = Some(
                    rest.trim()
                        .parse::<usize>()
                        .map_err(|e| format!("Line {}: invalid channels: {}", line_num + 1, e))?,
                );
            } else if let Some(rest) = trimmed.strip_prefix("synthetic:") {
                b.synthetic = Some(rest.trim().parse::<bool>().map_err(|e| {
                    format!("Line {}: invalid synthetic bool: {}", line_num + 1, e)
                })?);
            }
        }
    }

    if let Some(b) = current_entry.take() {
        entries.push(b.build(0)?);
    }

    Ok(CorpusManifest {
        version,
        description,
        entries,
    })
}

#[derive(Default)]
struct CorpusEntryBuilder {
    id: Option<String>,
    path: Option<String>,
    source: Option<String>,
    licence: Option<String>,
    sha256: Option<String>,
    duration: Option<f32>,
    sample_rate: Option<u32>,
    channels: Option<usize>,
    tags: Vec<String>,
    expected_test_uses: Vec<String>,
    synthetic: Option<bool>,
}

impl CorpusEntryBuilder {
    fn build(self, line_num: usize) -> Result<CorpusEntry, String> {
        let id = self
            .id
            .ok_or_else(|| format!("Line {}: entry missing 'id'", line_num))?;
        let path = self
            .path
            .ok_or_else(|| format!("Entry '{}' missing 'path'", id))?;
        let source = self
            .source
            .ok_or_else(|| format!("Entry '{}' missing 'source'", id))?;
        let licence = self
            .licence
            .ok_or_else(|| format!("Entry '{}' missing 'licence'", id))?;
        let sha256 = self
            .sha256
            .ok_or_else(|| format!("Entry '{}' missing 'sha256'", id))?;
        let duration = self
            .duration
            .ok_or_else(|| format!("Entry '{}' missing 'duration'", id))?;
        let sample_rate = self
            .sample_rate
            .ok_or_else(|| format!("Entry '{}' missing 'sample_rate'", id))?;
        let channels = self
            .channels
            .ok_or_else(|| format!("Entry '{}' missing 'channels'", id))?;
        let synthetic = self.synthetic.unwrap_or(false);

        Ok(CorpusEntry {
            id,
            path,
            source,
            licence,
            sha256,
            duration,
            sample_rate,
            channels,
            tags: self.tags,
            expected_test_uses: self.expected_test_uses,
            synthetic,
        })
    }
}

/// Serializes a `CorpusManifest` to YAML text.
pub fn serialize_manifest_yaml(manifest: &CorpusManifest) -> String {
    let mut out = String::new();
    out.push_str("# Flux Test Corpus Manifest (PLAN.md Appendix A)\n");
    out.push_str(
        "# Single source of truth for test fixture provenance, licences, and checksums.\n\n",
    );
    out.push_str(&format!("version: {}\n", manifest.version));
    out.push_str(&format!("description: \"{}\"\n\n", manifest.description));
    out.push_str("corpus:\n");

    for entry in &manifest.entries {
        out.push_str(&format!("  - id: {}\n", entry.id));
        out.push_str(&format!("    path: {}\n", entry.path));
        out.push_str(&format!("    source: {}\n", entry.source));
        out.push_str(&format!("    licence: {}\n", entry.licence));
        out.push_str(&format!("    sha256: {}\n", entry.sha256));
        out.push_str(&format!("    duration: {:.3}\n", entry.duration));
        out.push_str(&format!("    sample_rate: {}\n", entry.sample_rate));
        out.push_str(&format!("    channels: {}\n", entry.channels));
        out.push_str(&format!("    synthetic: {}\n", entry.synthetic));

        out.push_str("    tags:\n");
        for tag in &entry.tags {
            out.push_str(&format!("      - {}\n", tag));
        }

        out.push_str("    expected_test_uses:\n");
        for use_case in &entry.expected_test_uses {
            out.push_str(&format!("      - {}\n", use_case));
        }
        out.push('\n');
    }

    out
}

